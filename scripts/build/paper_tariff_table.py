#!/usr/bin/env python3
"""Per-tariff industry table and macros for the thesis, generated from the output files (nothing typed by hand).

    .venv/bin/python scripts/build/paper_tariff_table.py

Reads outputs/tables/tou_tariff_drift_step3.csv (baseline estimator) and tou_joint_regression_<tariff>.csv (with the
counterfactual-calendar controls; docs/specs/2026-11-26-joint-regression-design.md). Writes paper/tables/tariff_effects.tex and
paper/numbers_tariff.tex.
"""
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT / "scripts" / "analysis"))
import tou_tariff_drift as TD  # noqa: E402

T = ROOT / "outputs" / "tables"
E3 = T / "six_two_e3"
TARIFFS = ["6.2", "6.3", "6.4"]
f = lambda v: f"${v:+.2f}$".replace("+", "").replace("-", "-") if v < 0 else f"${v:.2f}$"
f3 = lambda v: f"${v:.3f}$"
pv = lambda p: "$<0.001$" if p < 0.001 else f"{p:.3f}"
ci = lambda lo, hi: f"[{f(lo)}, {f(hi)}]"


def main():
    # 6.2 is measured on E3 (ESIOS 1204, one population 2014-2026), not on 1216, which adds the 30-36 kV customers from
    # October 2018 (docs/specs/2026-11-27-six-two-constant-population-design.md, rule C2). The E3 run's Step 3 file holds
    # 6.3 and 6.4 unchanged and the pool on E3.
    s3 = pd.read_csv(E3 / "step3" / "tou_tariff_drift_step3.csv").set_index("series")
    rows_a, rows_b, mac = [], [], []
    names = {"6.2": "SixTwo", "6.3": "SixThree", "6.4": "SixFour"}
    for t in TARIFFS:
        r = s3.loc[t]
        rows_a.append((t, r.eta_2021, r.placebo_mean, r.placebo_sd, r.slope, r.slope_se,
                       (r.mean_effect, r.mean_lo, r.mean_hi, r.mean_p), (r.trend_effect, r.trend_lo, r.trend_hi, r.trend_p)))
        J = pd.read_csv((E3 / "joint" if t == "6.2" else T) / f"tou_joint_regression_{t}.csv")
        b = J[J.variant == "main"].set_index("summer").beta
        pl = b.drop(2021)
        mean, trend, slope, slope_se, m, sd = TD.nulls(float(b[2021]), pl.to_dict())
        rows_b.append((t, float(b[2021]), m, sd, slope, slope_se, (mean["eff"], mean["lo"], mean["hi"], mean["p"]),
                       (trend["eff"], trend["lo"], trend["hi"], trend["p"])))
        n = names[t]
        mac += [(f"Tar{n}Mean", mean["eff"]), (f"Tar{n}MeanLo", mean["lo"]), (f"Tar{n}MeanHi", mean["hi"]),
                (f"Tar{n}Trend", trend["eff"]), (f"Tar{n}TrendLo", trend["lo"]), (f"Tar{n}TrendHi", trend["hi"])]
        if t == "6.2":
            sep = pl.std(ddof=1) * (1 + 1 / len(pl)) ** 0.5
            from scipy import stats
            mac.append(("TarSixTwoBound", mean["eff"] - stats.t.ppf(0.95, len(pl) - 1) * sep))

    def panel(rows, title):
        out = [f"\\multicolumn{{7}}{{l}}{{\\textit{{{title}}}}}\\\\", "\\midrule"]
        for t, eta, m, sd, sl, se, me, tr in rows:
            out.append(f"{t} & {f(eta)} & {f(m)} ({sd:.3f}) & {f3(sl)} ({se:.3f}) & {f(me[0])} {ci(me[1], me[2])} & {f(tr[0])} {ci(tr[1], tr[2])} & {pv(me[3])} / {pv(tr[3])}\\\\")
        return out

    tex = ["% generated by scripts/build/paper_tariff_table.py; do not edit by hand",
           "\\begin{table}[htbp]\\centering\\small",
           "\\caption{Large-industry response to the regulated period price, by tariff (2021 against six placebo summers).}\\label{tab:tariffs}",
           "\\begin{threeparttable}",
           "\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{lcccccc}\\toprule",
           "Tariff & $\\eta_{2021}$ & Placebo mean (sd) & Placebo slope/yr (se) & Effect, mean null & Effect, trend null & $p$ (mean / trend)\\\\"]
    tex += panel(rows_a, "Panel A. Baseline estimator (Spain minus Portugal, one-year-out LASSO errors)")
    tex += ["\\midrule"] + panel(rows_b, "Panel B. With counterfactual-calendar controls (three principal components of shifted calendars)")
    tex += ["\\bottomrule\\end{tabular}}",
            "\\par\\smallskip\\parbox{\\textwidth}{\\footnotesize",
            "Effect = $\\eta_{2021}$ minus the no-reform value predicted from the six placebo summers 2014--2019 (their mean, or a straight line in year);",
            "brackets are 95\\% prediction intervals, $p$ one-sided. The pooled 6.2--6.4 figure hides the gradient with voltage. Only 6.4 passes all registered",
            "rules in Panel B (placebo slope not established, detected under both nulls); 6.3 narrows but its drift persists; 6.2 is negative under both nulls (one-sided $p$ 0.03--0.04) with intervals reaching just above zero, and the registered Panel B rules were not re-applied to it.",
            "6.2 is measured on the 36--72.5\\,kV series (E3), which covers the same customers in every year. Sources: \\texttt{docs/specs/2026-11-26-joint-regression-design.md}, \\texttt{docs/specs/2026-11-27-six-two-constant-population-design.md}.",
            "}\\end{threeparttable}\\end{table}"]
    (ROOT / "paper" / "tables").mkdir(exist_ok=True)
    (ROOT / "paper" / "tables" / "tariff_effects.tex").write_text("\n".join(tex) + "\n")
    lines = ["% generated by scripts/build/paper_tariff_table.py from outputs/tables (joint regression, mean and trend nulls)"]
    lines += [f"\\newcommand{{\\{k}}}{{\\ensuremath{{{v:.2f}}}}}" for k, v in mac]
    (ROOT / "paper" / "numbers_tariff.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
